#!/usr/bin/env bash
# Writes the start-page scenes audit.terminal.yaml and audit-narrow.terminal.yaml from
# examples/report.ansi, the real report the audit binary prints for tests/fixtures/bad with
# the config the Astro integration passes (examples/capture.sh). Nothing is reworded: the
# scene takes the summary with the top rules and the first two findings of index.html with
# their remedies; long lines are wrapped at spaces for the scene width.
# Rebuild the scenes afterwards:
#   cd site/captures && for f in audit.terminal.yaml audit-narrow.terminal.yaml; do
#     npx -y -p @casoon/castwright@0.5.0 -p shiki castwright build "$f" --format svg --loop-delay 10000 -o .; done
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
report="$here/../../examples/report.ansi"

# Summary and top rules (the first 11 lines), the file line, two findings with remedies.
excerpt="$(head -n 11 "$report"; sed -n '12,16p' "$report")"

# wrap <cols>: breaks long lines at spaces, counting visible characters only (no escape
# sequences, no bytes), and indents the continuation two columns deeper than the line.
wrap() {
  perl -CSD -ne '
    sub vis { my $s = shift; $s =~ s/\e\[[0-9;]*m//g; length $s }
    chomp; my ($ind) = /^( *)/; my $w = '"$1"';
    if (vis($_) <= $w) { print "$_\n"; next }
    my $cont = "$ind    "; my $out = $ind; my $line = "";
    for my $word (split / /, substr($_, length $ind)) {
      my $cand = $line eq "" ? $word : "$line $word";
      if (vis($out) + vis($cand) > $w && $line ne "") { print "$out$line\n"; $out = $cont; $line = $word }
      else { $line = $cand }
    }
    print "$out$line\n";
  '
}

# One YAML double-quoted string: ESC as \e, line ends as \r\n, quotes and backslashes escaped.
raw() {
  printf '%s\n' "$excerpt" | wrap "$1" | perl -0pe 's/\\/\\\\/g; s/"/\\"/g; s/\e/\\e/g; s/\n/\\r\\n/g; $_ = "\"$_\""'
}

# scene <file> <cols> <rows>: the same output, wrapped for <cols>; the narrow one is for
# phones, so the text keeps its size instead of shrinking.
scene() {
  cat > "$here/$1" <<YAML
# Generated by excerpt.sh from examples/report.ansi: an excerpt of a real report.
# Edit excerpt.sh, not this file.
version: 1
terminal:
  title: astro build · tests/fixtures/bad
  cols: $2
  rows: $3
  theme: catppuccin-mocha
steps:
  - wait: 400
  - output:
      raw: $(raw "$2")
  - wait: 6000
YAML
}

scene audit.terminal.yaml 64 22
scene audit-narrow.terminal.yaml 48 27
